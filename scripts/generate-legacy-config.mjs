#!/usr/bin/env node
/**
 * Emits the sys module's configuration as a TypeScript module.
 *
 * Templates read $gtitle, $charset, $gamecredits, $bbsurl and the rest of the
 * sys config. Those live in PHP files that are deliberately kept out of the
 * asset bundle, so the Worker needs their values another way.
 *
 * The values are read through the original interpreter, which means
 * interpolated ones such as $gamecredits (which embeds $gameversion) come out
 * exactly as the original would render them.
 *
 * Credentials are filtered on the PHP side and checked again here: database
 * settings, the authkey and the *_sign shared secrets never reach this file,
 * which matters because the repository is public.
 *
 * Usage: node scripts/generate-legacy-config.mjs [outputPath]
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const output = resolve(process.argv[2] ?? "src/generated/legacy-config.ts");
const bridge = resolve("tools/php-remote");
const php = process.env.DTS_PHP_BIN ?? (existsSync(bridge) ? bridge : "php");
const root = process.env.DTS_TEMPLATE_ROOT ?? "/opt/dts-sandbox/parity/instance";

const [result] = JSON.parse(
  execFileSync(php, ["scripts/php-template-reference.php"], {
    input: JSON.stringify({ root, cases: [{ action: "config" }] }),
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    timeout: 120000
  })
);

if (!result?.ok || typeof result.config !== "object") {
  console.error("Could not read the sys configuration through the original interpreter.");
  process.exit(1);
}

const FORBIDDEN = /pass|pwd|secret|key|token|salt|auth|sign|^db|gtablepre|server_address/i;
const leaked = Object.keys(result.config).filter(name => FORBIDDEN.test(name));
if (leaked.length > 0) {
  console.error(`Refusing to write credentials into a public repository: ${leaked.join(", ")}`);
  process.exit(1);
}

const entries = Object.entries(result.config).sort(([a], [b]) => a.localeCompare(b));

writeFileSync(
  output,
  `/**
 * Generated by scripts/generate-legacy-config.mjs. Do not edit.
 *
 * The sys module's configuration as the original interpreter evaluates it,
 * which is what templates read. Database settings, the authkey and the
 * *_sign shared secrets are excluded by the generator and must stay out.
 */
export const LEGACY_CONFIG = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;
`
);

console.log(`Wrote ${output}: ${entries.length} configuration values.`);
