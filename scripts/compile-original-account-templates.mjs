// Ahead-of-time translation only: Workers never evaluate PHP or dynamic JS.
// The PHP source compiler determines whitespace, language text and includes.
// Reject every unsupported AST node instead of dropping source expressions.
import fs from 'node:fs';
import Engine from 'php-parser';
const fixture = JSON.parse(fs.readFileSync(new URL('../test/fixtures/original-account-templates-php.json', import.meta.url)));
const parser = new Engine({ parser: { php7: true } });
const q = JSON.stringify;
function expr(n) {
  switch (n.kind) {
    case 'string': return q(n.value);
    case 'number': return String(Number(n.value));
    case 'variable':
      if (typeof n.name !== 'string') throw Error('Dynamic variables need an explicit port');
      return `v[${q(n.name)}]`;
    case 'name': return `constants[${q(n.name)}]`;
    case 'isset': return '(' + n.variables.map(v => `${expr(v)} != null`).join(' && ') + ')';
    case 'empty': return `!phpTruthy(${expr(n.expression)})`;
    case 'unary':
      if (n.type === '!') return `!phpTruthy(${expr(n.what)})`;
      break;
    case 'bin':
      if (n.type === '||' || n.type === '&&')
        return `(phpTruthy(${expr(n.left)}) ${n.type} phpTruthy(${expr(n.right)}))`;
      return `phpBinary(${q(n.type)}, ${expr(n.left)}, ${expr(n.right)})`;
    case 'retif': return `(phpTruthy(${expr(n.test)}) ? ${expr(n.trueExpr)} : ${expr(n.falseExpr)})`;
    case 'offsetlookup': return `phpOffset(${expr(n.what)}, ${expr(n.offset)})`;
    case 'assign':
      if (n.operator !== '=' || n.left.kind !== 'variable') break;
      return `(${expr(n.left)} = ${expr(n.right)})`;
    case 'call': {
      if (n.what.kind !== 'name') break;
      const args = n.arguments.map(expr);
      if (n.what.name === 'defined') return `Object.hasOwn(constants, phpString(${args[0]}))`;
      if (n.what.name === 'trim') return `phpString(${args[0]}).replace(/^[ \\n\\r\\t\\v\\0]+|[ \\n\\r\\t\\v\\0]+$/g, '')`;
      if (n.what.name === 'file_get_contents') return `readAssetText(phpString(${args[0]}))`;
      break;
    }
  }
  throw Error('Unported PHP expression: ' + JSON.stringify(n));
}
function statement(n) {
  switch (n.kind) {
    case 'block': return n.children.map(statement).join('\n');
    case 'inline': return `out += ${q(n.value)};`;
    case 'echo': return n.expressions.map(e => `out += phpString(${expr(e)});`).join('\n');
    case 'global':
      // Templates share their request-scoped symbol table, never module globals.
      return '';
    case 'if': return `if (phpTruthy(${expr(n.test)})) {\n${statement(n.body)}\n}` +
      (n.alternate ? ` else {\n${statement(n.alternate)}\n}` : '');
    case 'expressionstatement':
      if (n.expression.kind === 'exit') return `throw new Error(phpString(${expr(n.expression.expression)}));`;
      if (n.expression.kind === 'include') {
        const call = n.expression.target;
        if (call.kind !== 'call' || call.what.name !== 'template' || call.arguments[0].kind !== 'string') break;
        const name = call.arguments[0].value;
        if (!Object.hasOwn(fixture.compiled, name)) throw Error('Template not compiled: ' + name);
        return `out += render_${name}(v, constants, readAssetText);`;
      }
      return expr(n.expression) + ';';
  }
  throw Error('Unported PHP statement: ' + JSON.stringify(n));
}
let source = '// Generated by scripts/compile-original-account-templates.mjs. Do not hand-edit.\n' +
  '// Original compiler SHA256: ' + fixture.sourceCompilerSha256 + '\n' +
  'import { phpTruthy, phpString, phpBinary, phpOffset } from "../original-template-runtime";\n' +
  'import type { TemplateContext, TemplateConstants, TemplateReadAsset } from "../original-template-runtime";\n';
for (const [name, php] of Object.entries(fixture.compiled)) {
  source += `\n// ${fixture.sources[name].path} SHA256 ${fixture.sources[name].sha256}\n`;
  source += `function render_${name}(v: TemplateContext, constants: TemplateConstants, readAssetText: TemplateReadAsset): string {\nlet out = "";\n`;
  source += parser.parseCode(php).children.map(statement).join('\n') + '\nreturn out;\n}\n';
}
source += '\nexport const originalAccountTemplates = { login_page: render_login_page, error: render_error };\n';
source += 'export const originalAccountDefaults = ' + q(fixture.defaults) + ';\n';
source += 'export const originalErrorMessages: Readonly<Record<string, string>> = ' + q(fixture.errors) + ';\n';
source += 'export const originalAccountPolicy = ' + q(fixture.accountPolicy) + ';\n';
fs.writeFileSync(new URL('../src/generated/original-account-templates.ts', import.meta.url), source);
console.log('Compiled four original templates to static TypeScript.');
