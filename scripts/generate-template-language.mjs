#!/usr/bin/env node
/**
 * Emits the template pack's language map as a TypeScript module.
 *
 * parse_template substitutes {lang x} at compile time from
 * templates/default/templates.lang.php. That file is PHP, so it is
 * deliberately excluded from the asset bundle — serving it would disclose
 * source — and the Worker needs its contents some other way.
 *
 * The map is read through the original interpreter rather than by parsing the
 * file here, so the values are exactly what parse_template would have used.
 *
 * Usage: node scripts/generate-template-language.mjs [outputPath]
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const output = resolve(process.argv[2] ?? "src/generated/legacy-template-language.ts");
const bridge = resolve("tools/php-remote");
const php = process.env.DTS_PHP_BIN ?? (existsSync(bridge) ? bridge : "php");
const root = process.env.DTS_TEMPLATE_ROOT ?? "/opt/dts-sandbox/parity/instance";

const [result] = JSON.parse(
  execFileSync(php, ["scripts/php-template-reference.php"], {
    input: JSON.stringify({ root, cases: [{ action: "language" }] }),
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    timeout: 120000
  })
);

if (!result?.ok || typeof result.language !== "object") {
  console.error("Could not read templates.lang.php through the original interpreter.");
  process.exit(1);
}

const entries = Object.entries(result.language).sort(([a], [b]) => a.localeCompare(b));

writeFileSync(
  output,
  `/**
 * Generated by scripts/generate-template-language.mjs. Do not edit.
 *
 * templates/default/templates.lang.php as the original interpreter reads it.
 * parse_template substitutes {lang x} from this map at compile time.
 */
export const LEGACY_TEMPLATE_LANGUAGE: Readonly<Record<string, string>> = {
${entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`).join(",\n")}
};
`
);

console.log(`Wrote ${output}: ${entries.length} language entries.`);
