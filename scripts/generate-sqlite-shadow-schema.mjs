import { readFileSync, writeFileSync } from 'node:fs';
import {originalRoomSlots} from './lib/original-room-slots.mjs';
const {limit,slots}=originalRoomSlots();
const source = readFileSync('src/generated/legacy-schema.sql', 'utf8')+'\n'+slots.map(slot=>slot.sql).join('\n');
const tables = {};
const transport = {};
for (const m of source.matchAll(/CREATE TABLE IF NOT EXISTS "([^"]+)" \(([\s\S]*?)\n\);/g)) {
  const name = m[1];
  const body = m[2].replace(/bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g, 'INTEGER PRIMARY KEY AUTOINCREMENT').replace(/\bbigint\b/g, 'INTEGER');
  const pk = /"([^"]+)" INTEGER PRIMARY KEY/.exec(body)?.[1] ?? /PRIMARY KEY \("([^"]+)"\)/.exec(body)?.[1] ?? (name.endsWith('history') ? 'gid' : undefined);
  if (!pk) {
    if (name === 'acbra2_roomlisteners') {
      // Original PHP socket registrations have no counterpart in canonical
      // gameplay state. DO subscribers replace them; source queries still
      // operate on the exact original (empty) request-local transport table.
      transport[name]=`CREATE TABLE IF NOT EXISTS "${name}" (${body}\n);`;
      continue;
    }
    throw new Error('No primary key for '+name);
  }
  const indexes = [...source.matchAll(/CREATE UNIQUE INDEX IF NOT EXISTS "([^"]+)" ON "([^"]+)" \(([^;]+)\);/g)]
    .filter(x=>x[2]===name).map(x=>x[0]).join('\n');
  tables[name] = { primaryKey: pk, ddl: `CREATE TABLE IF NOT EXISTS "${name}" (${body}\n);\n${indexes}` };
}
const text = '// Generated by scripts/generate-sqlite-shadow-schema.mjs from the captured original schema.\n// Request-local SQL working copy only; Supabase remains authoritative.\nexport const LEGACY_SQLITE_SHADOW_SCHEMA: Readonly<Record<string, {primaryKey: string; ddl: string}>> = '+JSON.stringify(tables,null,2)+';\n'+
  'export const LEGACY_SQLITE_TRANSPORT_SCHEMA:Readonly<Record<string,string>> = '+JSON.stringify(transport,null,2)+';\n';
const output=text+'export const ORIGINAL_ROOM_ID_LIMIT='+limit+';\n';
const path='src/generated/legacy-sqlite-shadow-schema.ts';
if (process.argv.includes('--check')) { if(readFileSync(path,'utf8')!==output) throw new Error('Shadow schema is stale'); }
else writeFileSync(path,output);
console.log(Object.keys(tables).length+' original tables; no player data');
