#!/usr/bin/env node
/**
 * Deterministic manifest of static assets actually bundled in public/.
 * Workers have no filesystem; PHP file_exists and getimagesize must use this
 * captured inventory rather than assuming portraits do not exist.
 * No server-side PHP/configs or user records are embedded.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = join(root, "public");
const files = [];
function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (entry.isFile()) files.push(relative(directory, path).split(sep).join("/"));
  }
}
walk(directory);
files.sort();
const assetContent = [
  "// GENERATED by scripts/generate-public-static-files.mjs; do not edit.",
  "export const LEGACY_PUBLIC_STATIC_FILES: ReadonlySet<string> = new Set([",
  ...files.map(path => `  ${JSON.stringify(path)},`),
  "]);",
  ""
].join("\n");

function dimensions(bytes) {
  if (bytes.length >= 10 && bytes.subarray(0, 3).toString("ascii") === "GIF") {
    return [bytes.readUInt16LE(6), bytes.readUInt16LE(8)];
  }
  if (bytes.length >= 24 && bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10]))) {
    return [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
  }
  if (bytes.length >= 4 && bytes[0] === 255 && bytes[1] === 216) {
    let cursor = 2;
    while (cursor + 4 <= bytes.length) {
      if (bytes[cursor++] !== 255) break;
      while (bytes[cursor] === 255) cursor++;
      const marker = bytes[cursor++];
      if ([0xd9,0xda].includes(marker)) break;
      const size = bytes.readUInt16BE(cursor);
      if (size < 2 || cursor + size > bytes.length) break;
      if ([0xc0,0xc1,0xc2,0xc3,0xc5,0xc6,0xc7,0xc9,0xca,0xcb,0xcd,0xce,0xcf].includes(marker)) {
        return [bytes.readUInt16BE(cursor+5), bytes.readUInt16BE(cursor+3)];
      }
      cursor += size;
    }
  }
  return null;
}
const sizes = [];
for (const name of files) {
  if (!name.startsWith("img/")) continue;
  const pair = dimensions(readFileSync(join(directory, name)));
  if (pair && pair.every(n => Number.isInteger(n) && n > 0)) sizes.push([name, pair]);
}
const sizeContent = [
  "// GENERATED by scripts/generate-public-static-files.mjs; do not edit.",
  "// [width, height] of original public portraits as encoded in GIF/PNG/JPEG headers.",
  "export const LEGACY_PUBLIC_IMAGE_SIZES: ReadonlyMap<string, readonly [number, number]> = new Map([",
  ...sizes.map(([name, pair]) => `  [${JSON.stringify(name)}, [${pair[0]}, ${pair[1]}]],`),
  "]);",
  ""
].join("\n");
const outputs = [
  [join(root, "src/generated/legacy-public-static-files.ts"), assetContent],
  [join(root, "src/generated/legacy-public-image-sizes.ts"), sizeContent]
];
let stale = false;
for (const [path, content] of outputs) {
  if (process.argv.includes("--check")) {
    try {
      if (readFileSync(path, "utf8") !== content) stale = true;
    } catch { stale = true; }
  } else writeFileSync(path, content);
}
if (stale) {
  console.error("Original public asset manifests are stale.");
  process.exitCode = 1;
} else console.log(`${process.argv.includes("--check")?"Validated":"Generated"} ${files.length} static assets and ${sizes.length} image dimensions.`);
