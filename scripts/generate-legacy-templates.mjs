#!/usr/bin/env node
/**
 * Bundles the original's templates into the Worker.
 *
 * The page scripts include templates synchronously -- `include
 * template('register')` -- because PHP reads them off disk. A Worker
 * can reach them only through the asset binding, which is async, and
 * the interpreter running the original's code is synchronous
 * throughout. Preloading the one template a route needs is not enough
 * either: a template includes others, and which ones depends on the
 * data, so the set cannot be known before the page runs.
 *
 * So they are compiled in. All of them come to 2.9 MB against a 64 MiB
 * Worker limit, which makes this the cheap answer rather than a
 * compromise. The bytes are the captured original's, unchanged; the
 * same files are still served as assets for the browser.
 *
 * Usage: node scripts/generate-legacy-templates.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const templateRoot = join(repoRoot, "public/templates");
const OUTPUT = join(repoRoot, "src/generated/legacy-templates.ts");

const sources = new Map();
for (const set of readdirSync(templateRoot)) {
  for (const name of readdirSync(join(templateRoot, set))) {
    if (!name.endsWith(".htm")) continue;
    const text = readFileSync(join(templateRoot, set, name), "utf8");
    const bare = name.slice(0, -4);
    // Keyed every way the original asks for one: template() returns the
    // bare name, and some code builds the path itself.
    if (set === "default") sources.set(bare, text);
    sources.set(`${set}/${bare}`, text);
    sources.set(`./templates/${set}/${name}`, text);
  }
}

const lines = [
  "// GENERATED by scripts/generate-legacy-templates.mjs from",
  "//   public/templates/**/*.htm",
  "// Do not edit by hand.",
  "//",
  `// ${sources.size} keys over the captured template sets.`,
  "",
  "/** The original's template sources, keyed as its own code asks for them. */",
  "export const LEGACY_TEMPLATES: Record<string, string> = {"
];
for (const [key, text] of [...sources].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(text)},`);
}
lines.push("};", "");

writeFileSync(OUTPUT, lines.join("\n"));
console.log(`Wrote src/generated/legacy-templates.ts: ${sources.size} keys.`);
