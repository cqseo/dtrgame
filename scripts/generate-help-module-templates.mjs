#!/usr/bin/env node
/**
 * Embed every enabled original module template under both its MODULE_* alias
 * and the exact absolute path constructed by the PHP module loader.
 * No PHP source or user-controlled path is exposed through HTTP.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const original = resolve(process.env.DTS_LEGACY_ROOT ?? join(repo, "../legacy-dts"));
const registry = readFileSync(join(repo, "src/generated/legacy-registry.ts"), "utf8");
const start = registry.indexOf("[", registry.indexOf("export const LEGACY_MODULES"));
const end = registry.indexOf("] as const;", start);
if (start < 0 || end < 0) throw new Error("Cannot read original generated module registry.");
const modules = JSON.parse(registry.slice(start, end + 1));
const sourceFiles = new Map();
for (const module of modules) {
  if (!module.enabled) continue;
  for (const template of module.templates) {
    const relative = `include/modules/${module.path}${template}.htm`;
    // The original __INIT_MODULE__ defines a MODULE_*_TEMPLATE constant
    // equal to GAME_ROOT + './include/modules/...' without the .htm.
    const alias = `MOD_${module.name.toUpperCase()}_${template.toUpperCase().replaceAll("/", "_")}`;
    const source = readFileSync(join(original, relative), "utf8");
    const stem = `/./include/modules/${module.path}${template}`;
    for (const name of [alias, stem]) {
      const previous = sourceFiles.get(name);
      if (previous !== undefined && previous !== source) {
        throw new Error(`Conflicting original template alias: ${name}`);
      }
      sourceFiles.set(name, source);
    }
  }
}
const output = [
  "// GENERATED by scripts/generate-help-module-templates.mjs from the frozen original.",
  "// Do not edit by hand.",
  "export const LEGACY_HELP_MODULE_TEMPLATES: Readonly<Record<string, string>> = {"
];
for (const [name, source] of [...sourceFiles].sort(([a],[b])=>a.localeCompare(b))) {
  output.push(`  ${JSON.stringify(name)}: ${JSON.stringify(source)},`);
}
output.push("};", "");
const result = output.join("\n");
const destination = join(repo, "src/generated/legacy-help-module-templates.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== result) {
    console.error("Original module templates differ from the frozen original.");
    process.exitCode = 1;
  } else console.log(`Verified ${sourceFiles.size} original module template aliases.`);
} else {
  writeFileSync(destination, result);
  console.log(`Generated ${sourceFiles.size} original module template aliases.`);
}
