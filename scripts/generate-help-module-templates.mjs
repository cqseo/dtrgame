#!/usr/bin/env node
/**
 * Embed the original module templates addressed by the help page's
 * logical MOD_* template aliases. The original source stays read-only and
 * is never published as a downloadable PHP or template asset.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const original = resolve(process.env.DTS_LEGACY_ROOT ?? join(repo, "../legacy-dts"));
const sourceFiles = {
  MOD_CLUBBASE_SKILLPAGE: "include/modules/extra/club/clubbase/skillpage.htm",
  MOD_CLUBBASE_SKILLPAGE_PROFILE: "include/modules/extra/club/clubbase/skillpage_profile.htm"
};
const output = [
  "// GENERATED by scripts/generate-help-module-templates.mjs from the frozen original.",
  "// Do not edit by hand.",
  "export const LEGACY_HELP_MODULE_TEMPLATES: Readonly<Record<string, string>> = {"
];
for (const [name, path] of Object.entries(sourceFiles)) {
  output.push(`  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(original, path), "utf8"))},`);
}
output.push("};", "");
const result = output.join("\n");
const destination = join(repo, "src/generated/legacy-help-module-templates.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== result) {
    console.error("The embedded help module templates differ from the frozen original.");
    process.exitCode = 1;
  } else console.log("Help module templates match the original.");
} else {
  writeFileSync(destination, result);
  console.log(`Wrote ${destination} from ${Object.keys(sourceFiles).length} original templates.`);
}
